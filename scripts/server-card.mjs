import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import { Client, InMemoryTransport } from "@modelcontextprotocol/client";

import { createShareHtmlServer } from "../dist/server.js";

// Build-time discovery only. No API client, account, database or credentials are
// available, and even a future accidental tool invocation must fail the build.
let operationCalls = 0;
function forbiddenOperation() {
  operationCalls += 1;
  throw new Error("Server-card generation must never execute a tool.");
}

const server = createShareHtmlServer(
  {
    getRecipe: forbiddenOperation,
    generateDiagram: forbiddenOperation,
    listPages: forbiddenOperation,
    getPage: forbiddenOperation,
    publishPage: forbiddenOperation,
    publishPresentation: forbiddenOperation,
    updatePage: forbiddenOperation,
    publishExistingPage: forbiddenOperation,
    unpublishPage: forbiddenOperation,
    deletePage: forbiddenOperation,
  },
  {
    getSharing: forbiddenOperation,
    setSharing: forbiddenOperation,
    endCurrentViewingSessions: forbiddenOperation,
  },
  {
    previewArtifactStyle: forbiddenOperation,
    setArtifactStyle: forbiddenOperation,
    getArtifactStyle: forbiddenOperation,
  },
  {
    listTemplates: forbiddenOperation,
    getTemplate: forbiddenOperation,
    previewTemplate: forbiddenOperation,
    saveTemplate: forbiddenOperation,
  },
);
const client = new Client({ name: "server-card-build", version: "1.0.0" });
const [clientTransport, serverTransport] = InMemoryTransport.createLinkedPair();
let card;
try {
  await server.connect(serverTransport);
  await client.connect(clientTransport);
  const capabilities = client.getServerCapabilities();
  // If the server grows other discovery surfaces, include their definitions
  // deliberately rather than silently publishing an incomplete card.
  assert.equal(capabilities?.resources, undefined, "Add resource discovery to the card generator.");
  assert.equal(capabilities?.prompts, undefined, "Add prompt discovery to the card generator.");
  const tools = [];
  let cursor;
  const seenCursors = new Set();
  do {
    const result = await client.listTools(cursor ? { cursor } : {});
    tools.push(...result.tools);
    cursor = result.nextCursor;
    if (cursor) {
      assert.equal(seenCursors.has(cursor), false, "Repeated tool-list cursor.");
      seenCursors.add(cursor);
    }
  } while (cursor);
  assert.ok(tools.length > 0, "The server card must contain tool definitions.");
  // OpenAI requires explicit booleans; protocol defaults are insufficient for
  // review and can misrepresent the tool's effects to a calling client.
  for (const tool of tools) {
    for (const hint of ["readOnlyHint", "openWorldHint", "destructiveHint"]) {
      assert.equal(typeof tool.annotations?.[hint], "boolean",
        `${tool.name} must explicitly declare ${hint}.`);
    }
  }
  const serverInfo = client.getServerVersion();
  assert.ok(serverInfo?.name && serverInfo?.version);
  card = {
    serverInfo,
    authentication: { required: true, schemes: ["oauth2"] },
    tools,
    resources: [],
    prompts: [],
  };
} finally {
  await Promise.all([client.close(), server.close()]);
}
assert.equal(operationCalls, 0, "Tool execution occurred during discovery.");

// Keep generated bytes stable: no timestamps, hostnames, account data or secrets.
const serialized = `${JSON.stringify(card, null, 2)}\n`;
const destination = new URL("../dist/server-card.json", import.meta.url);
if (process.argv.includes("--check")) {
  assert.equal(await readFile(destination, "utf8"), serialized,
    "Server card differs from live SDK discovery; rebuild the MCP package.");
} else {
  await writeFile(destination, serialized);
}
console.log(`Server card ${process.argv.includes("--check") ? "verified" : "generated"}: ${card.tools.length} tools; no account operations.`);
